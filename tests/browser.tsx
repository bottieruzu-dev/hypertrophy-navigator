import React from 'react';
import { createRoot } from 'react-dom/client';
import Dexie from 'dexie';
import App from '../src/App';
import { db } from '../src/db/db';
import { EXERCISES } from '../src/db/seed/exercises';
import { CALIBRATION_PLAN } from '../src/db/queries/calibration';
import { seedDatabase } from '../src/db/seed';
import { buildDailyPlan } from '../src/engine/planner';
import { todayInJapan, shiftDate } from '../src/engine/dates';
import { startWorkout, logPlannedSet, correctLoggedSet, finishWorkout, skipExercise, replaceExercise } from '../src/db/queries/dailyPlan';
import { saveBaseline, retryPendingSync, newRecordId } from '../src/db/queries/workout';
import { restoreTrainingBackup } from '../src/db/queries/backup';
import { getRollingWeeklyCredit } from '../src/db/queries/weeklyCredit';
import { supabase } from '../src/lib/supabase';
import type { ExerciseBaseline, SetRecord } from '../src/db/types';
import type { TrainingBackup } from '../src/engine/backup';
import '../src/styles.css';

const report=document.getElementById('test-report')!;
const checks:string[]=[];
function check(ok:unknown,label:string) { if(!ok) throw new Error(label); checks.push(label); report.textContent=`${checks.length} checks passed · ${label}`; }
async function rejected(fn:()=>Promise<unknown>,label:string) { let failed=false; try { await fn(); } catch { failed=true; } check(failed,label); }
async function run() {
  if(import.meta.env.MODE!=='test' || db.name!=='HypertrophyNavigatorTestDB' || supabase!==null) throw new Error('Only the isolated test database and unconfigured cloud may be used.');
  await db.delete();
  // Reproduce an existing v1 installation, then perform the actual additive v2 migration.
  const legacy=new Dexie('HypertrophyNavigatorTestDB');
  legacy.version(1).stores({ muscles:'code, priorityRank, tag',exercises:'id, name, equipment, type, silhouetteTag, isAvailable',muscleCredits:'[exerciseId+muscle], exerciseId, muscle, credit',sessions:'++id, date, splitType, mesocycleWeek, isDeload',sets:'++id, sessionId, exerciseId, date, [exerciseId+date], [sessionId+setOrder]',bodyMetrics:'date',nutritionLogs:'date',cardioLogs:'++id, date',events:'++id, date, eventType, acknowledged',baselines:'exerciseId, calibratedAt',foods:'id, tag',settings:'key' });
  await legacy.open();
  const ids=Object.values(CALIBRATION_PLAN).flat();
  const baselines:ExerciseBaseline[]=EXERCISES.filter(e=>ids.includes(e.id)).map(e=>({exerciseId:e.id,weightKg:e.increment===0?0:e.id===1?12:50,reps:Math.floor((e.repRange[0]+e.repRange[1])/2),rir:2,est1rm:e.increment===0?0:70,calibratedAt:Date.parse(`${shiftDate(todayInJapan(),-14)}T12:00:00+09:00`)}));
  await legacy.table('baselines').bulkPut(baselines);
  await legacy.table('settings').bulkPut([{key:'programStartDate',value:'2026-09-01'},{key:'currentMesocycleWeek',value:3}]);
  await legacy.table('sessions').put({id:1,date:shiftDate(todayInJapan(),-7),startedAt:1,splitType:'upper_A',prsScore:null,sleepHours:null,mesocycleWeek:1,isDeload:0});
  const oldSet:SetRecord={id:1,sessionId:1,exerciseId:14,date:shiftDate(todayInJapan(),-7),setOrder:1,targetWeight:50,actualWeight:50,targetReps:12,actualReps:12,targetRir:2,actualRir:2,volumeLoad:600,est1rm:70,isWarmup:0,mode:'load'};
  await legacy.table('sets').put(oldSet);
  legacy.close(); await db.open(); await seedDatabase();
  check(await db.baselines.count()===26,'v1 → v2 preserves all 26 Week0 baselines');
  check((await db.settings.get('programStartDate'))?.value==='2026-09-01','seed migration preserves program start date');
  check((await db.settings.get('currentMesocycleWeek'))?.value===3,'seed migration preserves training week');
  check(await db.sets.count()===1,'legacy workout record survives migration');
  await saveBaseline(baselines[0]);
  check((await db.settings.get('calibrationDone'))?.value===true,'existing complete Week0 is recognized without restart');
  const data=async()=>({date:todayInJapan(),now:Date.now(),exercises:await db.exercises.toArray(),baselines:await db.baselines.toArray(),sets:await db.sets.toArray(),sessions:await db.sessions.toArray(),plans:await db.plans.toArray(),muscles:await db.muscles.toArray(),credits:await db.muscleCredits.toArray(),context:{minutes:60,readiness:'normal' as const,soreMuscles:[],pain:false,split:'upper_A' as const}});
  const draft=buildDailyPlan(await data());
  const plan=await startWorkout(draft);
  check(plan.sessionId!==1,'new session has an independent identity');
  check((await db.sessions.get(1))?.startedAt===1,'new sessions do not overwrite legacy session 1');
  await rejected(()=>startWorkout(draft),'duplicate starts are prevented atomically');
  const item=plan.exercises[0];
  await rejected(()=>logPlannedSet(plan.sessionId,item.exerciseId,{weight:-1,reps:10,rir:2,isWarmup:false}),'invalid set never writes');
  await logPlannedSet(plan.sessionId,item.exerciseId,{weight:item.targetWeight/2,reps:8,rir:4,isWarmup:true});
  check((await db.sets.where('sessionId').equals(plan.sessionId).toArray()).filter(s=>!s.isWarmup).length===0,'warmup does not count as a working set');
  await logPlannedSet(plan.sessionId,item.exerciseId,{weight:item.targetWeight,reps:item.targetReps,rir:2,isWarmup:false});
  const logged=(await db.sets.where('sessionId').equals(plan.sessionId).toArray()).find(s=>!s.isWarmup)!;
  check(logged.targetWeight===item.targetWeight && logged.targetReps===item.targetReps,'actual set stores the pre-existing prescription, not the next one');
  check(logged.date===todayInJapan(),'set records use the Japan gym day');
  await correctLoggedSet(logged.id!,{weight:item.targetWeight,reps:item.targetReps-1,rir:3});
  const corrected=await db.sets.get(logged.id!);
  check(corrected?.actualReps===item.targetReps-1 && corrected.targetReps===item.targetReps,'corrections change actual performance and preserve the prescription');
  check(await db.sets.where('sessionId').equals(plan.sessionId).count()===2,'correction does not create an extra set');
  check(!!(await db.plans.get(plan.sessionId))?.restEndsAt,'rest deadline is saved for reload recovery');
  await db.close(); await db.open();
  check((await db.plans.get(plan.sessionId))?.status==='active','active menu resumes after database reopen');
  check(await db.sets.where('sessionId').equals(plan.sessionId).count()===2,'sets survive reopen');
  await rejected(()=>finishWorkout(plan.sessionId,'completed'),'cannot complete an unfinished workout');
  await rejected(()=>replaceExercise(plan.sessionId,item.exerciseId,{...item,exerciseId:13}),'cannot replace an exercise after logging');
  const totals=await getRollingWeeklyCredit();
  check(totals.towardMax.lat===1,'rolling weekly volume excludes warmup and the eighth day');
  for(let n=1;n<item.sets;n++) await logPlannedSet(plan.sessionId,item.exerciseId,{weight:item.targetWeight,reps:item.targetReps,rir:2,isWarmup:false});
  await rejected(()=>logPlannedSet(plan.sessionId,item.exerciseId,{weight:item.targetWeight,reps:item.targetReps,rir:2,isWarmup:false}),'extra accidental taps cannot exceed the planned sets');
  for(const other of plan.exercises.slice(1)) await skipExercise(plan.sessionId,other.exerciseId);
  await finishWorkout(plan.sessionId,'completed');
  check((await db.sessions.get(plan.sessionId))?.finishedAt!==undefined,'completion records the finish time');
  await rejected(()=>logPlannedSet(plan.sessionId,item.exerciseId,{weight:50,reps:10,rir:2,isWarmup:false}),'finished sessions reject further sets');
  await rejected(()=>correctLoggedSet(logged.id!,{weight:50,reps:10,rir:2}),'finished sessions reject record corrections');
  check((await db.settings.where('key').startsWith('sync:').count())>0,'offline writes retain durable sync markers');
  check(await retryPendingSync()===false,'unconfigured cloud cannot report a successful sync');
  const before=await db.baselines.get(1);
  const backup:TrainingBackup={app:'HypertrophyNavigator',version:2,exportedAt:new Date().toISOString(),baselines:[{...before!,weightKg:99,calibratedAt:before!.calibratedAt+100}],sessions:[{...(await db.sessions.get(1))!,startedAt:9}],sets:[],plans:[]};
  await rejected(()=>restoreTrainingBackup(backup),'conflicting backups are rejected');
  check((await db.baselines.get(1))?.weightKg===before!.weightKg,'backup failure rolls back earlier baseline writes');
  const recordIds=Array.from({length:5000},newRecordId);
  check(new Set(recordIds).size===recordIds.length,'rapid ID generation does not collide');
  // Leave the app with intact dummy Week0 and no test sessions; the next UI flow starts fresh.
  await db.plans.clear();
  await db.sets.where('sessionId').equals(plan.sessionId).delete();
  await db.sessions.delete(plan.sessionId);
  await db.settings.where('key').startsWith('sync:').delete();
  report.textContent=`PASS · ${checks.length} database / migration checks · dummy data only`;
  report.dataset.result='pass';
  createRoot(document.getElementById('root')!).render(<React.StrictMode><App/></React.StrictMode>);
}
run().catch(error=>{report.textContent=`FAIL · ${String(error)} · after ${checks.length} checks`;report.dataset.result='fail';});
