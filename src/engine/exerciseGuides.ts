/** ガイドステップを取得する汎用関数（定義がない種目は型に応じて自動生成） */
export function getExerciseSteps(exercise: Exercise): ExerciseGuideStep[] {
  const custom = GUIDES_BY_ID[exercise.id];
  const rawTexts = custom ?? [
    `「${exercise.name}」ね！マシン・器具のセット完了？胸を張って準備しなさい！`,
    `主働筋をしっかり意識して、力強くポジティブ動作！効いている部分を感じて！`,
    `下ろす時（ネガティブ）を雑にしない！3秒かけて耐えながら負荷をコントロールよ！`,
    `ここからが筋肥大の本番！設定レップ数まで妥協せずにやり抜きなさい！`
  ];

  return [
    { stepNo: 1, title: "1. フォーム準備", text: rawTexts[0] },
    { stepNo: 2, title: "2. 収縮・効かせ", text: rawTexts[1] },
    { stepNo: 3, title: "3. ストレッチ耐え", text: rawTexts[2] },
    { stepNo: 4, title: "4. 目標完遂", text: rawTexts[3] },
  ];
}